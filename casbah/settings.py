def _load_local_api_vars() -> dict:
    """Local-dev only: read ~/.api_variables_env (export KEY=value), same file/format
    CASBAH-PrepareNewBuild already uses. The only secret CASBAH still needs from here is
    VAULT_TOKEN — everything else (NetBox/GitLab/vCenter creds) comes from Vault (see
    builds/vault_client.py), since Vault itself needs a token to bootstrap access with.
    JIRA_EMAIL/JIRA_API_TOKEN/VM_BUILDS_DIR below also read from this same file, since
    CASBAH is a personal tool now (see ai_prompt_revised.txt) sharing it with
    CASBAH-PrepareNewBuild rather than needing its own separate config.
    Returns {} if the file is missing."""
    path = Path.home() / ".api_variables_env"
    if not path.exists():
        return {}
    mode = stat.S_IMODE(path.stat().st_mode)
    if mode & (stat.S_IRWXG | stat.S_IRWXO):
        # Fail closed rather than silently reading a world/group-readable secrets file.
        return {}
    return {k: v for k, v in dotenv_values(path).items() if v}


